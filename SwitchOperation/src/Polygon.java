
public class Polygon {
public int display(int a)
{
	switch(a)
	{
	case 3:System.out.println("triangle");
	       break;
	case 4:System.out.println("square");
	       break;
	case 5:System.out.println("pentagon");
	       break;
	case 6:System.out.println("hexagon");
	       break;
	case 7:System.out.println("septagon");
	       break;
	case 8:System.out.println("octogon");
	       break;
	case 9:System.out.println("nanogon");
	}
	return a;
}
}
