
public class ArithemeticOperation {
public static int subtractNumbers(int x,int y)
{
	int res=x-y;
	System.out.println("the subtraction of number is"+res);
	return res;
}
public static int multiplyNumbers(int x,int y)
{
	int res=x*y;
	System.out.println("the multiplication of number is"+res);
	return res;
}
public static int divideNumbers(int x,int y)
{
	int res=x/y;
	System.out.println("the divide of the number is"+res);
	return res;
}
public static int findRemainder(int x,int y)
{
	int res=x%y;
	System.out.println("the remainder of the number is"+res);
	return res;
}
}

















